-- WebAlma: referencias de documentos PDF asociadas con pedidos.
-- No guarda bytes de documentos en PostgreSQL.
BEGIN;
CREATE TABLE IF NOT EXISTS public.documentos_impresion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id INTEGER NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
 detalle_id INTEGER NOT NULL REFERENCES public.detalle_pedido(id) ON DELETE CASCADE,
 telegram_file_id TEXT NOT NULL,
 nombre_archivo VARCHAR(120) NOT NULL,
 tamano_bytes INTEGER NOT NULL CHECK(tamano_bytes >= 0 AND tamano_bytes <= 8388608),
 paginas INTEGER NOT NULL CHECK(paginas BETWEEN 1 AND 200),
 copias INTEGER NOT NULL CHECK(copias BETWEEN 1 AND 30),
 tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('bn','color')),
 doble_cara BOOLEAN NOT NULL DEFAULT FALSE,
 formato VARCHAR(20) NOT NULL DEFAULT 'Otro',
 creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_documentos_impresion_pedido ON public.documentos_impresion(pedido_id);
COMMIT;
